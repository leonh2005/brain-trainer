"""
將 8x8 像素的 ASCII art tile 轉換為 NES CHR 格式（每 tile 16 bytes）
NES 使用 2-bit 顏色（平面 0 + 平面 1）
"""
import struct, sys

def tile_to_chr(rows):
    """rows: 8個字串，每個8個字元，使用 '.','1','2','3' 代表顏色0-3"""
    plane0 = []
    plane1 = []
    for row in rows:
        b0 = b1 = 0
        for i, c in enumerate(row[:8]):
            v = int(c) if c.isdigit() else 0
            if v & 1: b0 |= (0x80 >> i)
            if v & 2: b1 |= (0x80 >> i)
        plane0.append(b0)
        plane1.append(b1)
    return bytes(plane0 + plane1)

